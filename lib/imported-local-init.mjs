import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {schemaFingerprint} from './snapshot-d1-r2.mjs';
import {assertLocalMode,localWorkerConfig,LocalSetupError} from './local-runtime.mjs';
import {configureOfflineLocal} from './local-runtime.mjs';
import {installLocalNetworkGuard} from './local-network-guard.mjs';
import {acquireLocalStorageLease} from './local-storage-lease.mjs';
export async function initializeImportedLocal(root,args=[],environment=process.env){
  assertLocalMode(args,environment);
  if(fs.existsSync(path.join(root,'.sites-import.lock'))||!fs.existsSync(path.join(root,'.wrangler/COMPLETE'))||fs.existsSync(path.join(root,'.wrangler/FAILED')))throw new LocalSetupError('Snapshot import is incomplete; inspect its retained stage before startup');
  const receipt=JSON.parse(fs.readFileSync(path.join(root,'.wrangler/local-only/sites-snapshot-receipt.json'),'utf8'));
  if(receipt.format!=='PROCESS_OS_LOCAL_SNAPSHOT_RECEIPT_V1'||receipt.schemaFingerprint!==await schemaFingerprint()||receipt.dataReady!==true)throw new LocalSetupError('Imported snapshot receipt is incompatible');
  // No bootstrap, account verifier or signing secret is generated by this path.
  if(!fs.existsSync(path.join(root,'.wrangler/local-only/session.json')))throw new LocalSetupError('Local signing configuration requires separately authorized setup');
  const lease=acquireLocalStorageLease(root);
  configureOfflineLocal(root);installLocalNetworkGuard(root);
  const {getPlatformProxy}=createRequire(path.join(root,'package.json'))('wrangler');
  const proxy=await getPlatformProxy({configPath:path.join(root,'.wrangler/local-only/wrangler.json'),persist:{path:path.join(root,'.wrangler/state/v3')},remoteBindings:false,envFiles:[]});
  try{
    const row=await proxy.env.DB.prepare('SELECT "values" FROM shared_state WHERE id=1').first();
    const users=JSON.parse(JSON.parse(row?.values||'{}').platformUsers||'[]');
    if(!users.some(user=>user.enabled!==false&&!user.deletedAt&&user.authMode!=='demo'&&(user.passwordHash||user.password)))throw new LocalSetupError('Imported business data is ready; local account-verifier configuration still requires authorized setup');
  }finally{await proxy.dispose();lease.release();}
  return {snapshot:true,initialized:false,dataReady:true};
}
